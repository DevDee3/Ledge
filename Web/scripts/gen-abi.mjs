// Regenerate lib/abi.ts from the compiled contract so the frontend can never drift from it.
// Usage: node scripts/gen-abi.mjs ../ledge-contracts/out/LedgeRegistry.sol/LedgeRegistry.json
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/gen-abi.mjs <path to LedgeRegistry.json>");
  process.exit(1);
}
const { abi } = JSON.parse(readFileSync(src, "utf8"));
const body = `// GENERATED by scripts/gen-abi.mjs from the forge build output. Do not edit by hand.\nexport const ledgeRegistryAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
writeFileSync(new URL("../lib/abi.ts", import.meta.url), body);
console.log(`wrote lib/abi.ts (${abi.length} entries)`);
